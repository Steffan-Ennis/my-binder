async function main(): Promise<void> {
  const config = await loadConfig();

  await initDataSource({
    pgHost: config.pgHost,
    pgPort: config.pgPort,
    pgUser: config.pgUser,
    pgPassword: config.pgPassword,
    pgDatabase: config.pgDatabase,
    ssl: config.pgSsl,
  });
  const ds = getDataSource();

  const user = await ds.getRepository(UserEntity).findOneBy({ email: TARGET_EMAIL });
  if (!user) {
    throw new Error(
      `User not found for email "${TARGET_EMAIL}". Sign in once via the mobile app, then re-run.`,
    );
  }
  console.log(`Target user: ${user.email} (${user.id})`);

  const sdk = await MtgjsonSDK.create({ cacheDir: config.mtgjsonCacheDir });
  try {
    const cards = await sdk.cards.getByUuids(MTGJSON_UUIDS);
    const foundUuids = new Set(cards.map((c) => c.uuid));
    const missing = MTGJSON_UUIDS.filter((u) => !foundUuids.has(u));

    console.log(`MTGJSON resolved ${cards.length} / ${MTGJSON_UUIDS.length} UUIDs`);
    if (missing.length > 0) {
      console.warn(`Skipping ${missing.length} UUIDs not found in MTGJSON:`);
      for (const u of missing) console.warn(`  - ${u}`);
    }
    if (cards.length === 0) {
      console.log('Nothing to insert.');
      return;
    }

    const rows = cards.map((c) => ({ id: c.uuid, name: c.name, userId: user.id }));
    await ds.getRepository(CardEntity).upsert(rows, {
      conflictPaths: ['id', 'userId'],
      skipUpdateIfNoValuesChanged: true,
    });
    console.log(`Upserted ${rows.length} cards for ${user.email}`);
    for (const r of rows) console.log(`  ${r.id}  ${r.name}`);
  } finally {
    await sdk.close();
    await ds.destroy();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
